"""把 placements.json（place.py 的结果）和官方地名写成 Assets/AimTrainer/Editor/RealMapData.cs。坐标保持 glTF 原始坐标，由 RealMapBuilder 换算成 Unity 坐标。"""
import json, os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); CACHE = os.path.join(HERE, 'cache')
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
P = json.load(open(os.path.join(HERE, 'placements.json'), encoding='utf-8'))
en = [m for m in json.load(open(os.path.join(CACHE, 'maps_en.json'), encoding='utf-8'))['data'] if m['displayName'] == 'Ascent'][0]
zh = [m for m in json.load(open(os.path.join(CACHE, 'maps_zh.json'), encoding='utf-8'))['data'] if m['uuid'] == en['uuid']][0]
T = np.load(os.path.join(CACHE, 'ascent_col.npy')).reshape(-1, 3)
lo, hi = T.min(0), T.max(0); center = (lo + hi) / 2
def f(v): return f"{float(v):.3f}f".replace('.000f', 'f')
def v3(p): return f"new Vector3({f(p[0])}, {f(p[1])}, {f(p[2])})"
def s(t): return '"' + t.replace('"', '\\"') + '"'
out = ["// <auto-generated>由 tools/realmaps/emit.py 生成，请修改 tools/realmaps/spots.py 后重新运行 place.py 和 emit.py，不要直接改这里。</auto-generated>",
       "using AimTrainer.Game;", "using UnityEngine;", "", "namespace AimTrainer.EditorTools", "{",
       "    /// <summary>真实地图的训练数据（坐标是 glTF 原始坐标，米）。点位都经过碰撞网格检查：脚下有地面、身体不卡墙、路线上看得见。</summary>",
       "    public static class RealMapData", "    {",
       "        public static readonly RealMapBuilder.MapDefinition Ascent = new RealMapBuilder.MapDefinition",
       "        {",
       "            Scene = SceneCatalog.AscentRealScene,",
       '            Folder = "Assets/AimTrainer/RealMaps/Ascent",',
       '            Visual = "ascent-visual.glb",', '            Collision = "ascent-collision.glb",', '            Minimap = "ascent-minimap.png",',
       f"            CollisionCenterXZ = new Vector2({f(center[0])}, {f(center[2])}),",
       f"            MinimapX = new Vector2({repr(en['xMultiplier'])}f, {repr(en['xScalarToAdd'])}f),",
       f"            MinimapY = new Vector2({repr(en['yMultiplier'])}f, {repr(en['yScalarToAdd'])}f),",
       f"            Spawn = new RealMapBuilder.Spot(\"进攻方出生点\", {v3(P['spawn']['pos'])}, {v3(P['spawn']['face'])}),",
       f"            AimSpawn = new RealMapBuilder.Spot(\"甩枪出生点\", {v3(P['aim']['pos'])}, {v3(P['aim']['face'])}),",
       f"            AimArea = new RealMapBuilder.Area({v3(P['aim_area']['center'])}, {f(P['aim_area']['half'])}),",
       "            Callouts = new[]", "            {"]
for c, cz in zip(en['callouts'], zh['callouts']):
    sup = {'Attacker Side': '攻方', 'Defender Side': '守方'}.get(c['superRegionName'], cz['superRegionName'])
    out.append(f"                new RealMapBuilder.Callout({s(sup + ' ' + cz['regionName'])}, {f(c['location']['x'] / 100)}, {f(c['location']['y'] / 100)}),")
out += ["            },", "            Routes = new[]", "            {"]
for r in P['routes']:
    out.append(f"                new RealMapBuilder.Route({s(r['name'])}, new RealMapBuilder.Spot(\"起点\", {v3(r['start'])}, {v3(r['face'])}), new[]")
    out.append("                {")
    for p in r['points']:
        out.append(f"                    new RealMapBuilder.Spot({s(p['name'])}, {v3(p['pos'])}, {v3(p['face'])}),")
    out.append("                }),")
out += ["            },", "            Holds = new[]", "            {"]
for h in P['holds']:
    out.append(f"                new RealMapBuilder.Hold({s(h['name'])}, new RealMapBuilder.Spot(\"架枪位置\", {v3(h['pos'])}, {v3(h['face'])}), new[]")
    out.append("                {")
    for e in h['entries']:
        out.append(f"                    new RealMapBuilder.Entry({s(e['name'])}, {v3(e['pos'])}, {v3(e['to'])}),")
    out.append("                }),")
out += ["            },", "        };", "    }", "}", ""]
path = os.path.join(ROOT, 'Assets', 'AimTrainer', 'Editor', 'RealMapData.cs')
open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('已生成', path)
